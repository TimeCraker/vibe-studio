// 派生值生成器（设计即代码）：ffprobe 逐页音频时长 → 页时长/起点/总时长 → src/deck-params.ts；
// 页内各段按剥后字数比例在页音频窗内线性摊时 → src/deck-cues.ts（字段与首站 SubtitleCue 逐字段一致）。
// Usage: node scripts/build-deck-params.mjs <script.json> <deckDir>   （deckDir = public/deck）
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const OVERLAP_SECONDS = 0; // 硬切为底（v4 转场律）：页间零交叠，转场动词走 TransitionSeries
const BREATH_SECONDS = 0.4; // 音频后的页内呼吸
// 与 narration verify_narration.py 的剥离集一致：空白 + 中英标点
const STRIP = /[\s，。！？；：、\u201c\u201d\u2018\u2019（）《》…—,.!?;:'"()]/gu;

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const [scriptPath, deckDir] = process.argv.slice(2);
if (!scriptPath || !deckDir) {
  console.error(
    "usage: node scripts/build-deck-params.mjs <script.json> <deckDir>",
  );
  process.exit(1);
}

const script = JSON.parse(readFileSync(scriptPath, "utf8"));

// 按 ref "page N" 聚合段
const pages = new Map();
for (const seg of script.segments) {
  const m = /page\s+(\d+)/.exec(seg.ref ?? "");
  if (!m) {
    console.error(`segment ${seg.id}: ref not parseable: ${seg.ref}`);
    process.exit(1);
  }
  const page = Number(m[1]);
  if (!pages.has(page)) pages.set(page, []);
  pages.get(page).push(seg);
}

const r3 = (x) => Math.round(x * 1000) / 1000;
const probeSeconds = (wav) =>
  Number(
    execFileSync(
      "ffprobe",
      [
        "-v",
        "error",
        "-show_entries",
        "format=duration",
        "-of",
        "csv=p=0",
        wav,
      ],
      { encoding: "utf8" },
    ).trim(),
  );

const rows = [];
let cursor = 0;
for (const page of [...pages.keys()].sort((a, b) => a - b)) {
  const wav = join(deckDir, "audio", `page-${page}.wav`);
  if (!existsSync(wav)) {
    console.error(`missing audio: ${wav}`);
    process.exit(1);
  }
  const audioSeconds = r3(probeSeconds(wav));
  const pageSeconds = r3(audioSeconds + BREATH_SECONDS);
  rows.push({ index: page, start: r3(cursor), audioSeconds, pageSeconds });
  cursor = r3(cursor + pageSeconds);
}
const totalSeconds = r3(cursor + OVERLAP_SECONDS);

// 字幕摊时：页内各段按剥后字数比例摊进 [start, start + audioSeconds]
const cues = [];
for (const row of rows) {
  const segs = pages.get(row.index);
  const weights = segs.map((s) => [...s.text.replace(STRIP, "")].length);
  const totalChars = weights.reduce((a, b) => a + b, 0);
  const share = (i) =>
    totalChars > 0 ? weights[i] / totalChars : 1 / segs.length;
  let t = row.start;
  segs.forEach((seg, i) => {
    const dur = share(i) * row.audioSeconds;
    cues.push({ start: r3(t), end: r3(t + dur), text: seg.text });
    t = r3(t + dur);
  });
}

const paramsTs = `// AUTO-GENERATED by scripts/build-deck-params.mjs — 换素材/稿/配音后重跑，勿手改
export const deckParams = {
  fps: 30, width: 1920, height: 1080, overlapSeconds: ${OVERLAP_SECONDS},
  pages: [
${rows
  .map(
    (r) =>
      `    { index: ${r.index}, start: ${r.start}, audioSeconds: ${r.audioSeconds}, pageSeconds: ${r.pageSeconds} },`,
  )
  .join("\n")}
  ],
  totalSeconds: ${totalSeconds},
} as const;
`;

const cuesTs = `// AUTO-GENERATED by scripts/build-deck-params.mjs — 勿手改
export const deckCues: { start: number; end: number; text: string }[] = [
${cues
  .map(
    (c) =>
      `  { start: ${c.start}, end: ${c.end}, text: ${JSON.stringify(c.text)} },`,
  )
  .join("\n")}
];
`;

writeFileSync(join(root, "src", "deck-params.ts"), paramsTs);
writeFileSync(join(root, "src", "deck-cues.ts"), cuesTs);

console.log(
  `deck: ${rows.length} pages, total ${totalSeconds}s, ${cues.length} cues -> src/deck-params.ts + src/deck-cues.ts`,
);
